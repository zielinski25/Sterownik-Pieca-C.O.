// [LCD-IKONY] Bitmapy 32x32, 1-bit (MSB-first, wiersz padowany do pelnych bajtow -
// przy 32px to rowno 4 bajty/wiersz, zero bitow marginesu bo 32 jest juz
// wielokrotnoscia 8). Wygenerowane offline z ksztaltow wektorowych, renderowanych
// z 8x nadprobkowaniem i zmniejszonych z filtrem LANCZOS, zeby krawedzie byly
// gladkie/antyaliasowane zamiast "schodkowe" jak przy recznym fillTriangle/fillCircle.
// Uzycie: tft.drawBitmap(x, y, IKONA_PLOMIEN, 32, 32, kolor) -> bity=1 rysowane sa na
// "kolor", bity=0 sa przezroczyste (tlo bez zmian), wiec ten sam bitmap dziala z KAZDYM
// kolorem stanu (dokladnie jak wczesniejsze rysujIkonaXXX).
//
// [FIX tej sesji, "sporo wolnego miejsca kolo ikony"] Powiekszone z 24x24 na
// 32x32 - user: "ikona ma spora przestrzen wolna, zwieksz moze ikony". Realna
// przyczyna byla dwojaka: (1) ikona 24px w karcie 114x90 zostawiala duzo
// nieuzytej przestrzeni po prawej-gornej stronie, (2) wartosc (font 28,
// line_height=30 wg realnych metryk lv_font_montserrat_28.c z repo LVGL -
// .line_height=30, .base_line=5) siedziala tuz pod etykieta (y=30) z 26-27px
// martwej przestrzeni miedzy nia a dolem karty. 32x32 to JUZ UZYWANY w tym
// projekcie rozmiar (BOJLER, POMPA) - powiekszenie DYM/ZEWN/PLOMIEN/KROPLA/
// SUWAK/CISNIENIE/POKOJ do tej samej wartosci ujednolica cala siatke zamiast
// tworzyc trzeci rozmiar. GRZEJNIK (kafelek PIEC CO/SR, 3 wiersze w tej samej
// wysokosci karty) zostal CELOWO przy 24px - patrz IKONA_GRZEJNIK_ROZMIAR
// nizej - bo ten kafelek ma mniej pionowego zapasu (3 wiersze zamiast 2) i
// przeliczenie pokazalo kolizje glownej wartosci z wierszem SR przy 32px
// ikonie; nie zostal ruszony w tej turze.
// [FIX tej sesji - odtworzenie utraconej pracy] IKONA_ROZMIAR 32->40,
// IKONA_ZEWN_ROZMIAR 32->40, IKONA_BOJLER_ROZMIAR 32->40 (user: "wszystkie
// ikony mozna rozciagnac bo jest miejsce"). GRZEJNIK (IKONA_GRZEJNIK_ROZMIAR)
